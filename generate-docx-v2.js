// ===== Helpers =====
function h(text, level) {
  return new Paragraph({
    heading: level,
    spacing: { before: level <= 2 ? 400 : 280, after: 160 },
    children: [new TextRun({ text, bold: true, font: 'Microsoft YaHei' })]
  });
}
function p(text, opts = {}) {
  return new Paragraph({
    spacing: { after: 120, line: 360 },
    children: [new TextRun({ text, font: 'Microsoft YaHei', size: 22, ...opts })]
  });
}
function bp(parts) {
  // parts: [{text, bold, color, ...}]
  const children = parts.map(pt => new TextRun({ text: pt.text, font: 'Microsoft YaHei', size: 22, bold: !!pt.bold, color: pt.color || '000000' }));
  return new Paragraph({ spacing: { after: 120, line: 360 }, children });
}
function bullet(parts, indent = 0) {
  const children = parts.map(pt => new TextRun({ text: pt.text, font: 'Microsoft YaHei', size: 22, bold: !!pt.bold, color: pt.color || '000000' }));
  return new Paragraph({
    spacing: { after: 80, line: 340 },
    indent: { left: convertInchesToTwip(0.4 + indent * 0.4) },
    children: [new TextRun({ text: '• ', font: 'Microsoft YaHei', size: 22 }), ...children]
  });
}
function numItem(num, parts, indent = 0) {
  const children = parts.map(pt => new TextRun({ text: pt.text, font: 'Microsoft YaHei', size: 22, bold: !!pt.bold, color: pt.color || '000000' }));
  return new Paragraph({
    spacing: { after: 80, line: 340 },
    indent: { left: convertInchesToTwip(0.4 + indent * 0.4) },
    children: [new TextRun({ text: num + ' ', font: 'Microsoft YaHei', size: 22 }), ...children]
  });
}
function divider() {
  return new Paragraph({ spacing: { before: 120, after: 120 }, border: { bottom: { style: BorderStyle.SINGLE, size: 6, color: 'CCCCCC' } }, children: [] });
}
function createTable(headers, rows, colWidths) {
  const headerRow = new TableRow({
    tableHeader: true,
    children: headers.map((h, i) =>
      new TableCell({
        shading: { type: ShadingType.SOLID, color: '2F5496', fill: '2F5496' },
        width: { size: colWidths ? colWidths[i] : 4500, type: WidthType.DXA },
        children: [new Paragraph({
          alignment: AlignmentType.CENTER,
          spacing: { before: 40, after: 40 },
          children: [new TextRun({ text: h, bold: true, color: 'FFFFFF', font: 'Microsoft YaHei', size: 20 })]
        })]
      })
    )
  });
  const dataRows = rows.map((row, ri) =>
    new TableRow({
      children: row.map((cell, ci) =>
        new TableCell({
          width: { size: colWidths ? colWidths[ci] : 4500, type: WidthType.DXA },
          shading: ri % 2 === 0 ? { type: ShadingType.SOLID, color: 'F2F7FC', fill: 'F2F7FC' } : undefined,
          children: [new Paragraph({
            spacing: { before: 30, after: 30 },
            children: [new TextRun({ text: cell, font: 'Microsoft YaHei', size: 20 })]
          })]
        })
      )
    })
  );
  return new Table({
    width: { size: 100, type: WidthType.PERCENTAGE },
    rows: [headerRow, ...dataRows]
  });
}
function exampleBox(title, lines) {
  const children = [];
  children.push(new Paragraph({
    spacing: { before: 60, after: 40 },
    shading: { type: ShadingType.SOLID, color: 'E8F0FE', fill: 'E8F0FE' },
    children: [new TextRun({ text: '【示例】' + title, font: 'Microsoft YaHei', size: 20, bold: true, color: '2F5496' })]
  }));
  lines.forEach(line => {
    children.push(new Paragraph({
      spacing: { after: 30 },
      shading: { type: ShadingType.SOLID, color: 'F8FAFE', fill: 'F8FAFE' },
      indent: { left: convertInchesToTwip(0.3) },
      children: [new TextRun({ text: line, font: 'Microsoft YaHei', size: 20 })]
    }));
  });
  return children;
}

